-- Q6 Find itemid of items which has either been ordered or not delivered (UNION)

SELECT ITEMID
FROM ORDERS
UNION
SELECT ITEMID
FROM ORDERS
WHERE ORDERID NOT IN (SELECT ORDERID FROM DELIVERY);


-- Q7 Find names of customers who placed orders and their orders delivered (INTERSECT)

SELECT CUSTNAME
FROM CUSTOMERS
WHERE CUSTID IN (SELECT CUSTID FROM ORDERS)

INTERSECT

SELECT CUSTNAME
FROM CUSTOMERS
WHERE CUSTID IN (
    SELECT O.CUSTID
    FROM ORDERS O
    JOIN DELIVERY D
    ON O.ORDERID = D.ORDERID
);


-- Q8 Customers who placed orders but not delivered (MINUS)

