-- Q9 Customer who placed the most number of orders

SELECT CUSTNAME
FROM CUSTOMERS
WHERE CUSTID =
(
    SELECT CUSTID
    FROM ORDERS
    GROUP BY CUSTID
    HAVING COUNT(*) = (
        SELECT MAX(COUNT(*))
        FROM ORDERS
        GROUP BY CUSTID
    )
);


-- Q10 Customers who purchased items costing more than 5000

SELECT DISTINCT C.*
FROM CUSTOMERS C
JOIN ORDERS O ON C.CUSTID = O.CUSTID
JOIN ITEMS I ON O.ITEMID = I.ITEMID
WHERE I.PRICE > 5000;


-- Q11 Customers who have not ordered Samsung Galaxy S4

SELECT CUSTNAME, ADDRESS
FROM CUSTOMERS
WHERE CUSTID NOT IN
(
    SELECT O.CUSTID
    FROM ORDERS O
    JOIN ITEMS I ON O.ITEMID = I.ITEMID
    WHERE I.ITEMNAME = 'Samsung Galaxy S4'
);


-- Q12 LEFT OUTER JOIN

SELECT *
FROM CUSTOMERS C
LEFT JOIN ORDERS O
ON C.CUSTID = O.CUSTID;


-- Q12 RIGHT OUTER JOIN

SELECT *
FROM CUSTOMERS C
RIGHT JOIN ORDERS O
ON C.CUSTID = O.CUSTID;


-- Q13 Customers grouped by state

SELECT STATE, COUNT(*) AS TOTAL_CUSTOMERS
FROM CUSTOMERS
GROUP BY STATE;


-- Q14 Items grouped by category with price greater than average price

SELECT CATEGORY, AVG(PRICE)
FROM ITEMS
GROUP BY CATEGORY
HAVING AVG(PRICE) > (SELECT AVG(PRICE) FROM ITEMS);
